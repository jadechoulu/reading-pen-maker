// 真实成品验收：仅替代原生文件选择框，导入、试听、生成和重启均使用应用真实实现。
const { _electron } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const validation = process.env.VALIDATION_DIR;
if (!validation || !path.isAbsolute(validation)) throw new Error('请用 VALIDATION_DIR 指定新的绝对验收路径');
const appPath = process.env.APP_PATH;
if (!appPath) throw new Error('请指定 APP_PATH');
const executablePath = path.join(appPath, 'Contents', 'MacOS', 'Electron');
const profile = path.join(validation, 'profile');
const fixtures = path.join(validation, '输入'), outputs = path.join(validation, '输出');
const ffmpeg = path.join(appPath, 'Contents', 'Resources', 'runtime', 'ffmpeg');
const report = { appPath, arch: 'x64', hardware: 'Apple Silicon + Rosetta', nativeIntelTest: 'not_performed', penTest: 'not_performed', checks: [], errors: [] };
let desktop, page;
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
async function launch(files) {
  desktop = await _electron.launch({ executablePath, args: [`--user-data-dir=${profile}`], timeout: 60000 });
  page = await desktop.firstWindow({ timeout: 60000 });
  await desktop.evaluate(({ app }) => { process.getBuiltinModule('module').createRequire(app.getAppPath()+'/package.json')('./app/main.cjs').getUpdater().settings.autoCheck = false; });
  page.on('pageerror', error => report.errors.push(error.message));
  await page.waitForFunction(() => window.xkd && !document.querySelector('#new-book').disabled);
  await page.context().setOffline(true);
  await desktop.evaluate(({ dialog }, input) => {
    dialog.showOpenDialog = async (_window, options) => ({ canceled: false, filePaths: options.properties.includes('openDirectory') ? [input.outputs] : input.files });
  }, { files, outputs });
  return page;
}
async function ready() { await page.waitForFunction(() => !document.querySelector('#new-book').disabled); }
(async () => {
  await fs.mkdir(validation); await fs.mkdir(fixtures); await fs.mkdir(outputs);
  const files = ['10000-1.mp3', '10000-2.mp3', '小狗.mp3'].map(name => path.join(fixtures, name));
  for (let i = 0; i < files.length; i++) execFileSync(ffmpeg, ['-nostdin', '-v', 'error', '-f', 'lavfi', '-i', `sine=frequency=${440 + i * 220}:duration=0.8`, '-ac', '2', '-ar', '48000', '-codec:a', 'libmp3lame', '-b:a', '96k', files[i]]);
  const before = await Promise.all(files.map(async file => hash(await fs.readFile(file))));
  await launch(files);
  await page.locator('#welcome').waitFor();
  assert.equal(await desktop.evaluate(() => process.arch), 'x64');
  await page.screenshot({ path: path.join(validation, '01_欢迎页.png'), fullPage: true });
  await page.locator('#welcome-create').click(); await page.locator('#new-title').fill('小狗的声音');
  await page.locator('#create-form button[type=submit]').click(); await ready();
  await page.locator('#empty-import').click(); await ready();
  assert.equal(await page.locator('#tracks tr').count(), 3);
  assert.equal(await page.getByRole('textbox', { name: '点读码 1', exact: true }).inputValue(), '10000');
  assert.equal(await page.getByRole('textbox', { name: '点读码 2', exact: true }).inputValue(), '10000');
  assert.equal(await page.getByRole('textbox', { name: '点读码 3', exact: true }).inputValue(), '');
  await page.locator('#export').click(); await ready();
  assert.match(await page.locator('#notice').textContent(), /请填写/);
  assert.deepEqual(await fs.readdir(outputs), []);
  report.checks.push('Intel 成品离线启动，建立书籍并导入真实 MP3；自动识别同一码多段文件，缺码时拒绝生成');
  await page.getByRole('textbox', { name: '点读码 3', exact: true }).fill('abc');
  await page.locator('#save').click(); await ready(); assert.match(await page.locator('#notice').textContent(), /点读码/);
  await page.getByRole('textbox', { name: '点读码 3', exact: true }).fill('');
  await page.locator('#assign').click(); await page.locator('#start-code').fill('10000');
  await page.locator('#assign-form button[type=submit]').click();
  assert.equal(await page.getByRole('textbox', { name: '点读码 3', exact: true }).inputValue(), '10001');
  assert.equal(await page.getByRole('textbox', { name: '点读码 1', exact: true }).inputValue(), '10000');
  await page.getByRole('textbox', { name: '点读码 3', exact: true }).fill('10002');
  await page.getByRole('textbox', { name: '音频说明 1', exact: true }).fill('小狗英文');
  await page.getByRole('button', { name: '下移音频 1', exact: true }).click();
  await page.locator('#save').click(); await ready();
  let snapshot = await page.evaluate(() => window.xkd.list());
  assert.deepEqual(snapshot.books[0].tracks.map(t => t.name), ['10000-2.mp3', '10000-1.mp3', '小狗.mp3']);
  assert.equal(snapshot.books[0].tracks[2].oid, '10002');
  await page.getByRole('button', { name: '试听音频 1', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#player').duration > 0.5 && !document.querySelector('#player').paused);
  await page.locator('#close-player').click();
  await page.screenshot({ path: path.join(validation, '02_制作界面.png'), fullPage: true });
  report.checks.push('手动填码、无效码拒绝、调整多段顺序与修改说明保存；成品内置播放器可真实解码播放');
  await page.locator('#export').click(); await ready();
  assert.match(await page.locator('#notice').textContent(), /NOB 已生成并通过/);
  snapshot = await page.evaluate(() => window.xkd.list());
  const result = snapshot.books[0].exports[0];
  assert.equal(result.points, 2); assert.equal(result.audios, 3);
  assert.equal(result.audioRecompressed, false);
  assert.equal(hash(await fs.readFile(result.output)), result.sha256);
  report.output = result;
  // 使用另一语言、另一路实现的既有 NOB 读取器验证结构和每段真实音频，不调用 JS 生成器的校验函数。
  const python = process.env.REFERENCE_PYTHON || 'python3';
  const script = "import sys,json;from pathlib import Path;from package_tool import inspect_nob;m=inspect_nob(Path(sys.argv[1]).read_bytes());print(json.dumps(m,ensure_ascii=False))";
  const model = JSON.parse(execFileSync(python, ['-c', script, result.output], { cwd: path.join(__dirname, 'reference'), encoding: 'utf8' }));
  assert.deepEqual(model.points.map(p => p.oid), [10000, 10002]); assert.equal(model.unsupported.length, 0);
  assert.deepEqual(model.identity.oid_ranges, [[10000, 10000], [10002, 10002]]);
  assert.equal(model.checks.unparsed_nonzero_record_bytes, 0); assert.equal(model.checks.audio_region_fully_referenced, true);
  assert.equal(model.identity.customer_id, 54); assert.equal(model.identity.book_id, 0);
  const expectedNames = ['10000-2.mp3', '10000-1.mp3', '小狗.mp3'], audioHashes = [];
  for (let i = 0; i < expectedNames.length; i++) {
    audioHashes.push(hash(await fs.readFile(path.join(fixtures, expectedNames[i]))));
  }
  const byId = new Map(model.audios.map(a => [a.id, a.sha256]));
  assert.deepEqual(model.points.flatMap(p => p.audio_refs.map(id => byId.get(id))), audioHashes);
  await fs.writeFile(path.join(validation, '独立Python核对.json'), JSON.stringify(model, null, 2));
  assert.deepEqual(await Promise.all(files.map(async file => hash(await fs.readFile(file)))), before);
  report.checks.push('真实 FFmpeg 完整解码检查；NOB 内三段 48kHz 双声道 MP3 与源文件逐字节一致，未重编码；独立 Python 验证全部点位、顺序、范围和校验');
  await page.screenshot({ path: path.join(validation, '03_生成完成.png'), fullPage: true });
  await page.locator('#export').click(); await ready();
  snapshot = await page.evaluate(() => window.xkd.list());
  assert.equal(snapshot.books[0].exports.length, 2); assert.notEqual(snapshot.books[0].exports[0].output, result.output);
  assert.equal(hash(await fs.readFile(result.output)), result.sha256);
  await desktop.close(); desktop = null;
  await launch(files); await page.locator('#editor').waitFor();
  snapshot = await page.evaluate(() => window.xkd.list());
  assert.equal(snapshot.books[0].title, '小狗的声音'); assert.equal(snapshot.books[0].tracks[1].label, '小狗英文');
  assert.equal(snapshot.books[0].tracks.length, 3); assert.equal(snapshot.books[0].exports.length, 2);
  await page.locator('#help').click(); await page.locator('#help-dialog').waitFor(); await page.locator('#close-help').click();
  await page.getByRole('button', { name: '移除音频 3', exact: true }).click(); await ready();
  assert.equal(await page.locator('#tracks tr').count(), 2);
  assert.deepEqual(await Promise.all(files.map(async file => hash(await fs.readFile(file)))), before);
  report.checks.push('重复生成保留旧成品；关闭重开保留书籍、顺序、说明和两条记录；移出音频不删除原件');
  const cloudFiles = [path.join(fixtures, '云盘音频.wma'), files[0], path.join(fixtures, '坏音频.wma')];
  execFileSync(ffmpeg, ['-nostdin', '-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=660:duration=1.1', '-ac', '2', '-ar', '44100', '-codec:a', 'wmav2', '-b:a', '128k', cloudFiles[0]]);
  await fs.writeFile(cloudFiles[2], 'invalid audio');
  const cloudBefore = await Promise.all(cloudFiles.map(async file => hash(await fs.readFile(file))));
  await desktop.evaluate(({ dialog }, input) => { dialog.showOpenDialog = async (_window, options) => ({ canceled: false, filePaths: options.properties.includes('openDirectory') ? [input.outputs] : input.files }); }, { files: cloudFiles, outputs });
  await page.locator('#batch-open').click(); await page.locator('#batch-choose').click(); await ready();
  assert.equal(await page.locator('#batch-files li').count(), 3);
  await page.locator('#batch-start').click(); await ready();
  assert.match(await page.locator('#batch-result').textContent(), /成功 2 个，失败 1 个/);
  assert.equal(await page.locator('#batch-results li').count(), 3);
  await page.screenshot({ path: path.join(validation, '04_批量转MP3.png'), fullPage: true });
  const batchFolder = (await fs.readdir(outputs)).find(name => name.startsWith('毛毛虫云盘_MP3_ABR128_'));
  const batch = JSON.parse(await fs.readFile(path.join(outputs, batchFolder, '转换记录.json')));
  assert.equal(batch.targetKbps, 128); assert.equal(batch.mode, 'ABR');
  for (const row of batch.results.filter(row => row.ok)) {
    const bytes = await fs.readFile(path.join(batch.folder, row.outputName));
    assert.ok(bytes.indexOf(Buffer.from('Xing')) >= 0);
  }
  assert.deepEqual(await Promise.all(cloudFiles.map(async file => hash(await fs.readFile(file)))), cloudBefore);
  report.checks.push('独立毛毛虫云盘工具：以 libmp3lame -abr 1 -b:a 128k 处理真实 WMA 和 MP3，输出变码率 MP3 通过完整解码及时长核对；坏文件单独失败，原件不变');
  report.batch = batch;
  await page.locator('#batch-close').click();
  assert.deepEqual(report.errors, []); report.allPassed = true;
})().catch(error => { report.allPassed = false; report.errors.push(error.stack); process.exitCode = 1; console.error(error); }).finally(async () => {
  if (desktop) await desktop.close().catch(() => {});
  await fs.writeFile(path.join(validation, '桌面验收结果.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
});
